#!/usr/bin/env Rscript

# Annotate Leafcutter detected introns (Parallel version)

suppressMessages(library(data.table))
suppressMessages(library(argparser))
suppressMessages(library(stringr))
suppressMessages(library(dplyr))
suppressMessages(library(magrittr))
suppressMessages(library(parallel))

# =========================
# Argument parsing
# =========================
p <- arg_parser("Annotate Leafcutter introns (Parallel)")
p <- add_argument(p, "--annot", help="annotation code generated by leafviz")
p <- add_argument(p, "--counts", help="perind numers file generated by leafcutter")
p <- add_argument(p, "--outdir", help="Output directory")
p <- add_argument(p, "--ncores", help="Number of cores to use", default=2)

args <- parse_args(p)

counts_file <- args$counts
annotation_code <- args$annot
ncores <- as.integer(args$ncores)

# =========================
# Load annotation files
# =========================
intron_db <- fread(paste0(annotation_code, "_all_introns.bed.gz"), data.table=FALSE)
colnames(intron_db)[1:4] <- c("chr","start","end","gene")

threeprime_db <- fread(paste0(annotation_code, "_threeprime.bed.gz"), data.table=FALSE)
colnames(threeprime_db)[1:7] <- c("chr","start","end","gene","gene_id","strand","transcript")

fiveprime_db <- fread(paste0(annotation_code, "_fiveprime.bed.gz"), data.table=FALSE)
colnames(fiveprime_db)[1:7] <- c("chr","start","end","gene","gene_id","strand","transcript")

# =========================
# Load counts
# =========================
counts <- fread(counts_file, data.table=FALSE)

all.introns <- as.data.frame(str_split_fixed(counts$chrom, ":", 4), stringsAsFactors=FALSE)
names(all.introns) <- c("chr","start","end","clusterID")
all.introns$start <- as.numeric(all.introns$start)
all.introns$end <- as.numeric(all.introns$end)
all.junctions <- all.introns %>% select(chr, start, end, clusterID)

# =========================
# Prepare intersect tables
# =========================
all.introns_intersect <- all.junctions %>%
  left_join(intron_db, by=c("chr","start","end"))

threeprime_intersect <- all.junctions %>%
  select(chr, clusterID, start=end) %>%
  left_join(threeprime_db, by=c("chr","start"))

fiveprime_intersect <- all.junctions %>%
  select(chr, clusterID, start) %>%
  left_join(fiveprime_db, by=c("chr","start"))

clusters <- unique(all.introns$clusterID)

# =========================
# Function for processing one cluster
# =========================
process_cluster <- function(clu) {
  cluster <- all.introns %>% filter(clusterID == clu)
  fprimeClu <- fiveprime_intersect %>% filter(clusterID == clu)
  tprimeClu <- threeprime_intersect %>% filter(clusterID == clu)
  bothSSClu <- all.introns_intersect %>% filter(clusterID == clu)

  fprime <- cluster %>% left_join(fprimeClu, by=c("chr","start"))
  tprime <- cluster %>% left_join(tprimeClu, by=c("chr"="chr","end"="start"))
  bothSS <- cluster %>% left_join(bothSSClu, by=c("chr","start","end"))

  cluster_gene <- names(sort(table(c(tprime$gene, fprime$gene)), decreasing=TRUE))[1]
  if (is.null(cluster_gene)) cluster_gene <- "."

  gene_strand <- NA
  if (cluster_gene != ".") {
    strands <- c(tprime$strand, fprime$strand)
    gene_strand <- unique(strands[!is.na(strands) & strands != "."])
    if (length(gene_strand) != 1) gene_strand <- NA
  }

  if (cluster_gene != ".") {
    cluster_ensemblID <- unique(unlist(c(
      fprime %>% filter(gene == cluster_gene) %>% select(gene_id),
      tprime %>% filter(gene == cluster_gene) %>% select(gene_id)
    )))
  } else {
    cluster_ensemblID <- "."
  }

  verdict <- vector("character", nrow(cluster))
  coord <- character(nrow(cluster))
  gene <- rep(cluster_gene, nrow(cluster))
  ensemblID <- rep(cluster_ensemblID, nrow(cluster))
  transcripts <- vector("list", nrow(cluster))

  for (i in seq_len(nrow(cluster))) {
    intron <- cluster[i,]
    coord[i] <- paste(intron$chr, intron$start, intron$end)

    f_intron <- intron %>% left_join(fprime, by=c("chr","start"))
    t_intron <- intron %>% left_join(tprime, by=c("chr","end"))
    b_intron <- intron %>% left_join(bothSSClu, by=c("chr","start","end"))

    transcripts[[i]] <- intersect(t_intron$transcript, f_intron$transcript)

    unknown_3p <- all(is.na(t_intron$gene))
    unknown_5p <- all(is.na(f_intron$gene))

    verdict[i] <- "error"

    if (is.na(gene_strand)) {
      verdict[i] <- "unknown_strand"
    } else if (unknown_3p & unknown_5p) {
      verdict[i] <- "cryptic_unanchored"
    } else if (
      (unknown_3p & !unknown_5p & gene_strand == "+") |
      (unknown_5p & !unknown_3p & gene_strand == "-")
    ) {
      verdict[i] <- "cryptic_threeprime"
    } else if (
      (!unknown_3p & unknown_5p & gene_strand == "+") |
      (!unknown_5p & unknown_3p & gene_strand == "-")
    ) {
      verdict[i] <- "cryptic_fiveprime"
    } else if (is.na(gene_strand) & (!unknown_3p | !unknown_5p)) {
      verdict[i] <- "cryptic"
    } else if (!unknown_3p & !unknown_5p) {
      if (all(!is.na(b_intron$gene))) {
        verdict[i] <- "annotated"
      } else {
        verdict[i] <- "novel annotated pair"
      }
    }
  }

  all_transcripts <- unique(unlist(transcripts))
  all_transcripts <- all_transcripts[all_transcripts != "."]

  constitutive <- lapply(transcripts, function(x) {
    x <- x[x != "."]
    length(x) / length(all_transcripts)
  })

  transcripts_collapsed <- lapply(transcripts, function(x) paste(x, collapse="+"))

  list(
    clusterID=clu,
    verdict=verdict,
    coord=coord,
    gene=gene,
    ensemblID=ensemblID,
    transcripts=transcripts_collapsed,
    constitutive=constitutive
  )
}

# =========================
# Run in parallel
# =========================
cat("Running parallel annotation with", ncores, "cores...\n")

results <- mclapply(clusters, process_cluster, mc.cores=ncores)

# =========================
# Combine results
# =========================
verdict.list <- setNames(lapply(results, `[[`, "verdict"), sapply(results, `[[`, "clusterID"))
coord.list <- setNames(lapply(results, `[[`, "coord"), sapply(results, `[[`, "clusterID"))
gene.list <- setNames(lapply(results, `[[`, "gene"), sapply(results, `[[`, "clusterID"))
ensemblID.list <- setNames(lapply(results, `[[`, "ensemblID"), sapply(results, `[[`, "clusterID"))
transcripts.list <- setNames(lapply(results, `[[`, "transcripts"), sapply(results, `[[`, "clusterID"))
constitutive.list <- setNames(lapply(results, `[[`, "constitutive"), sapply(results, `[[`, "clusterID"))

# Save everything
save(
  all.introns,
  verdict.list,
  coord.list,
  gene.list,
  ensemblID.list,
  transcripts.list,
  constitutive.list,
  file=file.path(args$outdir, "leafviz.RData")
)

cat("Done.\n")